"""A minimal MCP server (Streamable HTTP, JSON-RPC 2.0) for the stand-up agent.

MeetStream's MIA agent calls this during a stand-up to look someone up live,
e.g. when a person joins who was not on the pre-loaded roster. Read-only.
Auth: ``Authorization: Bearer <mcp_token>`` (generated by the app).
"""
from __future__ import annotations

import hmac
import json
from typing import Any, Dict

from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy.orm import Session

from app.db import get_db
from app.models import Meeting
from app.services import identity, standup
from app.services.app_settings import get_setting

router = APIRouter(tags=["mcp"])

TOOLS = [
    {
        "name": "get_person_context",
        "description": "Get a team member's open work items, blockers and last update by name, to follow up in the stand-up.",
        "inputSchema": {"type": "object", "properties": {"name": {"type": "string"}}, "required": ["name"]},
    },
    {
        "name": "list_standup_roster",
        "description": "List the people expected in the current stand-up for a bot.",
        "inputSchema": {"type": "object", "properties": {"bot_id": {"type": "string"}}, "required": []},
    },
]


def _auth(request: Request, db: Session) -> None:
    token = get_setting(db, "mcp_token")
    header = request.headers.get("Authorization", "")
    if not token or not hmac.compare_digest(header.removeprefix("Bearer ").strip(), token):
        raise HTTPException(401, "Invalid MCP token")


def _call(db: Session, name: str, args: Dict[str, Any]) -> str:
    if name == "get_person_context":
        emp = identity.match_employee(str(args.get("name", "")), identity.active_employees(db))
        if not emp:
            return f"No team member called {args.get('name')!r} is on record."
        return json.dumps(standup.person_context(db, emp, Meeting(slot="general")))
    if name == "list_standup_roster":
        meeting = db.query(Meeting).filter(Meeting.bot_id == args.get("bot_id")).first() if args.get("bot_id") else None
        people = standup.roster(db, meeting) if meeting else identity.active_employees(db)
        return ", ".join(p.name for p in people) or "No roster."
    raise HTTPException(400, f"Unknown tool {name}")


@router.post("/mcp")
async def mcp(request: Request, db: Session = Depends(get_db)):
    _auth(request, db)
    body = await request.json()
    rid, method, params = body.get("id"), body.get("method"), body.get("params") or {}
    if method == "initialize":
        result = {"protocolVersion": "2024-11-05", "capabilities": {"tools": {"listChanged": False}},
                  "serverInfo": {"name": "meetpact", "version": "1.0.0"}}
    elif method == "tools/list":
        result = {"tools": TOOLS}
    elif method == "tools/call":
        text = _call(db, params.get("name"), params.get("arguments") or {})
        result = {"content": [{"type": "text", "text": text}]}
    elif method and method.startswith("notifications/"):
        return {}
    else:
        return {"jsonrpc": "2.0", "id": rid, "error": {"code": -32601, "message": f"Unknown method {method}"}}
    return {"jsonrpc": "2.0", "id": rid, "result": result}
